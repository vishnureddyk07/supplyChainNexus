from __future__ import annotations

import json
import os
from datetime import timedelta
from uuid import NAMESPACE_URL, uuid5

import psycopg

from services.event_consumer.event_store import EventStore
from services.graph.service import SupplyChainGraph
from services.demo.scenario import DEMO_LABEL_SOURCE, scenario_for_today


def main() -> None:
    if os.getenv("APP_ENV") != "development-demo":
        raise RuntimeError("demo seed refuses to run unless APP_ENV=development-demo")
    dsn = os.environ["DATABASE_URL"]
    scenario = scenario_for_today()
    store = EventStore(dsn)
    graph = SupplyChainGraph.from_env()
    try:
        for event in scenario.events:
            store.persist(event)
            graph.upsert_event(event)
            store.mark_graph_projected(event.event_id)

        with psycopg.connect(dsn, connect_timeout=10) as connection:
            with connection.cursor() as cursor:
                for shipment in scenario.shipments:
                    cursor.execute(
                        """
                        INSERT INTO shipments (
                            shipment_id, supplier_external_id,
                            origin_name, origin_latitude, origin_longitude,
                            destination_name, destination_latitude, destination_longitude,
                            planned_departure, planned_arrival, actual_arrival, simulated
                        )
                        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, TRUE)
                        ON CONFLICT (shipment_id) DO UPDATE SET
                            supplier_external_id = EXCLUDED.supplier_external_id,
                            origin_name = EXCLUDED.origin_name,
                            origin_latitude = EXCLUDED.origin_latitude,
                            origin_longitude = EXCLUDED.origin_longitude,
                            destination_name = EXCLUDED.destination_name,
                            destination_latitude = EXCLUDED.destination_latitude,
                            destination_longitude = EXCLUDED.destination_longitude,
                            planned_departure = EXCLUDED.planned_departure,
                            planned_arrival = EXCLUDED.planned_arrival,
                            actual_arrival = EXCLUDED.actual_arrival,
                            simulated = TRUE
                        """,
                        (
                            shipment.shipment_id,
                            shipment.supplier_id,
                            shipment.origin_name,
                            shipment.origin_latitude,
                            shipment.origin_longitude,
                            shipment.destination_name,
                            shipment.destination_latitude,
                            shipment.destination_longitude,
                            shipment.planned_departure,
                            shipment.planned_arrival,
                            shipment.actual_arrival,
                        ),
                    )
                for supplier_id, score, category, scored_at in scenario.risk_labels:
                    cursor.execute(
                        """
                        INSERT INTO supplier_risk_scores (
                            supplier_id, risk_score, risk_category,
                            score_source, scored_at, created_by, updated_by
                        )
                        SELECT id, %s, %s, %s, %s, 'demo-scenario-v1', 'demo-scenario-v1'
                        FROM suppliers
                        WHERE external_id = %s
                        ON CONFLICT (supplier_id, scored_at)
                            WHERE score_source = 'demo_synthetic'
                        DO UPDATE SET
                            risk_score = EXCLUDED.risk_score,
                            risk_category = EXCLUDED.risk_category
                        """,
                        (
                            score,
                            category,
                            DEMO_LABEL_SOURCE,
                            scored_at,
                            supplier_id,
                        ),
                    )
                for index, supplier_id in enumerate(scenario.disruption_suppliers):
                    cursor.execute(
                        """
                        INSERT INTO disruption_log (
                            id, supplier_id, disruption_type, severity,
                            description, source, detected_at, simulated,
                            created_by, updated_by
                        )
                        SELECT %s, id, 'simulated_operational_disruption',
                               'medium', 'Generated by deterministic demo scenario.',
                               'demo-scenario-v1', %s, TRUE,
                               'demo-scenario-v1', 'demo-scenario-v1'
                        FROM suppliers WHERE external_id = %s
                        ON CONFLICT (id) DO UPDATE SET
                            detected_at = EXCLUDED.detected_at,
                            simulated = TRUE
                        """,
                        (
                            uuid5(
                                NAMESPACE_URL,
                                f"scn-demo-disruption:{supplier_id}:{scenario.anchor.date()}",
                            ),
                            scenario.anchor - timedelta(days=index + 1),
                            supplier_id,
                        ),
                    )
                cursor.execute(
                    """
                    INSERT INTO incidents (
                        id, title, description, severity, status, owner,
                        supplier_external_id, investigation_notes, simulated
                    )
                    VALUES (
                        %s, 'Demo: elevated supplier telemetry',
                        'Synthetic incident for demonstration only.',
                        'high', 'investigating', 'Demo Operations',
                        %s, 'Inspect the associated simulated telemetry and model evidence.',
                        TRUE
                    )
                    ON CONFLICT (id) DO UPDATE SET
                        status = EXCLUDED.status,
                        owner = EXCLUDED.owner,
                        simulated = TRUE
                    """,
                    (
                        uuid5(NAMESPACE_URL, "scn-demo-incident:telemetry-v1"),
                        scenario.risk_labels[0][0],
                    ),
                )

        for supplier_id, upstream_supplier_id in scenario.dependencies:
            graph.upsert_supply_dependency(
                supplier_id,
                upstream_supplier_id,
                simulated=True,
            )
    finally:
        graph.close()

    print(
        json.dumps(
            {
                "scenario": "deterministic-demo-v1",
                "synthetic": True,
                "event_count": len(scenario.events),
                "supplier_count": len(scenario.risk_labels),
                "shipment_count": len(scenario.shipments),
                "risk_label_count": len(scenario.risk_labels),
                "dependency_count": len(scenario.dependencies),
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
